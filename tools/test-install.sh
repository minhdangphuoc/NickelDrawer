#!/bin/bash
# Exercises tools/install-to-kobo.sh against a fake Kobo tree in a temp dir. Never touches a real volume.
# Needs `make build dist` first.
set -euo pipefail

REPO_ROOT=$(cd "$(dirname "$0")/.." && pwd)
INSTALLER=$REPO_ROOT/tools/install-to-kobo.sh
WORK=$(mktemp -d)
export KOBO_ROOT=$WORK/KOBOeReader
# Backups of the installer land in the temp dir, so a test never touches the real backups/.
export BACKUP_ROOT=$WORK/backups
export MOD_TGZ=$WORK/mod/KoboRoot-nickeldrawer.tgz
ADDS=$KOBO_ROOT/.adds
failures=0

trap 'rm -rf "$WORK"' EXIT

check() {
    local description=$1
    shift
    if "$@"; then
        echo "ok   - $description"
    else
        echo "FAIL - $description"
        failures=$((failures + 1))
    fi
}

contains() { grep -qF -- "$2" "$1"; }
lacks() { ! grep -qF -- "$2" "$1"; }

write_kobo_conf() {
    mkdir -p "$KOBO_ROOT/.kobo/Kobo"
    printf '[ApplicationPreferences]\nCurrentLocale=%s\n' "$1" >"$KOBO_ROOT/.kobo/Kobo/Kobo eReader.conf"
}

build_fake_kobo() {
    mkdir -p "$KOBO_ROOT/.kobo" "$ADDS/nm" "$ADDS/localsend"
    write_kobo_conf vi
    cp "$REPO_ROOT/tools/testdata/legacy-nm-items.txt" "$ADDS/nm/items"
    echo '#!/bin/sh' >"$ADDS/localsend/start.sh"
    printf '# generated by appsctl\nmenu_item :main :LocalSend · Start receiving :cmd_output :9500 :/x\n' >"$ADDS/nm/koboapps"
}

installed_backup_count() { ls "$BACKUP_ROOT" | wc -l | tr -d ' '; }

build_fake_kobo
cp "$ADDS/nm/items" "$WORK/items.original"

echo "--- dry run"
"$INSTALLER" --dry-run >"$WORK/dry.out"
check "dry run creates no koboapps folder" test ! -e "$ADDS/koboapps"
check "dry run prints actions" contains "$WORK/dry.out" "[dry-run]"
check "dry run keeps the generated menu file" test -f "$ADDS/nm/koboapps"
check "dry run leaves the NickelMenu tab setting alone" cmp -s "$ADDS/nm/items" "$WORK/items.original"
check "dry run announces the tab change" contains "$WORK/dry.out" "set experimental:menu_main_15505_enabled:0"

echo "--- first install"
mkdir -p "$ADDS/apps" "$ADDS/koboapps"
echo junk >"$ADDS/apps/._x"
echo junk >"$ADDS/nm/.DS_Store"
echo junk >"$ADDS/koboapps/._y"
"$INSTALLER" >"$WORK/first.out"
check "appsctl installed and executable" test -x "$ADDS/koboapps/bin/appsctl"
check "localgo installed and executable" test -x "$ADDS/apps/localsend/bin/localgo"
check "ghsync installed" test -x "$ADDS/apps/ghsync/bin/ghsync"
check "wallpaper installed" test -x "$ADDS/apps/wallpaper/bin/wallpaper"
check "wallpaper scripts installed" test -x "$ADDS/apps/wallpaper/bin/import.sh"
check "wallpaper locales installed" test -f "$ADDS/apps/wallpaper/locales/vi.json"
check "library installed" test -x "$ADDS/apps/library/bin/library"
check "library scripts installed" test -x "$ADDS/apps/library/bin/scan.sh"
check "library ui.json installed" test -f "$ADDS/apps/library/ui.json"
check "library locales installed" test -f "$ADDS/apps/library/locales/vi.json"
check "todo helper installed and executable" test -x "$ADDS/apps/todo/bin/todo"
check "todo scripts installed" test -x "$ADDS/apps/todo/bin/state.sh"
check "todo ui.json installed" test -f "$ADDS/apps/todo/ui.json"
check "todo locales installed" test -f "$ADDS/apps/todo/locales/vi.json"
check "todo icon installed" test -f "$ADDS/apps/todo/icon.png"
check "todo ships no task list" test ! -e "$ADDS/apps/todo/data/todo.json"
check "uikit scripts installed" test -x "$ADDS/apps/uikit/bin/state.sh"
check "uikit ui.json installed" test -f "$ADDS/apps/uikit/ui.json"
check "uikit component pages installed" test -f "$ADDS/apps/uikit/screens/button.json"
check "uikit viewer page installed" test -f "$ADDS/apps/uikit/screens/viewer.json"
check "uikit echo script installed" test -x "$ADDS/apps/uikit/bin/echo.sh"
check "uikit locales installed" test -f "$ADDS/apps/uikit/locales/vi.json"
check "uikit icon installed" test -f "$ADDS/apps/uikit/icon.png"
check "uikit ships hidden" contains "$ADDS/apps/uikit/app.json" '"hidden": true'
check "config.example.json installed" test -f "$ADDS/apps/ghsync/config.example.json"
check "ghsync ships no data files" test "$(ls "$ADDS/apps/ghsync/data" | wc -l | tr -d ' ')" = 0
check "host icons installed" test -f "$ADDS/koboapps/icons/refresh.png"
check "More-row apps icon installed" test -f "$ADDS/koboapps/icons/apps.png"
check "UI icon installed" test -f "$ADDS/koboapps/icons/ui/settings-64.png"
check "app icon installed" test -f "$ADDS/apps/localsend/icon.png"
check "drawer row icon (64 px) installed" test -f "$ADDS/apps/localsend/icon-64.png"
check "chevron icon installed" test -f "$ADDS/koboapps/icons/ui/chevron-right-64.png"
check "locales installed (host)" test -f "$ADDS/koboapps/locales/vi.json"
check "routing.json installed" test -f "$ADDS/koboapps/config/routing.json"
check "routing.json lists the epub rule" contains "$ADDS/koboapps/config/routing.json" '"type": "epub"'
check "inbox folder created" test -d "$ADDS/koboapps/inbox"
check "inbox/rejected folder created" test -d "$ADDS/koboapps/inbox/rejected"
check "project.json shipped" contains "$ADDS/koboapps/config/project.json" '"repo": "minhdangphuoc/NickelDrawer"'
check "update.json template names the project repo" contains "$ADDS/koboapps/config/update.json" '"repo": "minhdangphuoc/NickelDrawer"'
check "data/update.json created with the default repo" contains "$ADDS/koboapps/data/update.json" '"repo": "minhdangphuoc/NickelDrawer"'
check "no user routing.json created by the installer" test ! -e "$ADDS/koboapps/data/routing.json"
check "localsend routes through the inbox hook" contains "$ADDS/apps/localsend/bin/env.sh" "inbox route --from-env --source localsend"
check "locales installed (app)" test -f "$ADDS/apps/localsend/locales/vi.json"
check "update-apply.sh installed and executable" test -x "$ADDS/koboapps/bin/update-apply.sh"
check "update-check.sh installed and executable" test -x "$ADDS/koboapps/bin/update-check.sh"
check "retired update-status.sh not shipped" test ! -e "$ADDS/koboapps/bin/update-status.sh"
check "settings screen installed" test -f "$ADDS/koboapps/screens/settings/ui.json"
check "settings screen locale installed" test -f "$ADDS/koboapps/screens/settings/locales/vi.json"
check "retired updates screen not shipped" test ! -e "$ADDS/koboapps/screens/updates"
check "flag folder created" test -d "$ADDS/nickeldrawer"
check "the screens flag is not created (screens are on by default)" test ! -e "$ADDS/nickeldrawer/screens"
check "no debug flag by default" test ! -e "$ADDS/nickeldrawer/debug"
check "no mod staged when no mod was built" test ! -e "$KOBO_ROOT/.kobo/KoboRoot.tgz"
check "generated NickelMenu app file removed" test ! -e "$ADDS/nm/koboapps"
check "generated NickelMenu app file backed up" grep -rqF "LocalSend · Start receiving" "$BACKUP_ROOT"/*/.adds/nm/koboapps
check "no NickelMenu app items generated" test -z "$(find "$ADDS/nm" -name 'koboapps*')"
check "NickelMenu tab switched off" contains "$ADDS/nm/items" "experimental:menu_main_15505_enabled:0"
check "NickelMenu tab line appears once" test "$(grep -c "menu_main_15505_enabled" "$ADDS/nm/items")" = 1
check "other tab settings untouched" contains "$ADDS/nm/items" "experimental :menu_main_15505_0_enabled: 1"
check "reader-menu Dark Mode item untouched" contains "$ADDS/nm/items" "menu_item :reader :Dark Mode"
check "only the tab line changed in items" test "$(diff "$WORK/items.original" "$ADDS/nm/items" | grep -c '^[<>]')" = 2
check "legacy items kept without --remove-legacy" contains "$ADDS/nm/items" "Nhận sách LocalSend"
check "legacy folder kept without --remove-legacy" test -d "$ADDS/localsend"
check "AppleDouble file in .adds/apps removed" test ! -e "$ADDS/apps/._x"
check ".DS_Store in .adds/nm removed" test ! -e "$ADDS/nm/.DS_Store"
check "AppleDouble file in .adds/koboapps removed" test ! -e "$ADDS/koboapps/._y"
check "backup created" test "$(installed_backup_count)" -ge 1

echo "--- second install keeps data"
echo "secret-token" >"$ADDS/apps/ghsync/data/token"
echo '{"repo":"o/r"}' >"$ADDS/apps/ghsync/data/config.json"
echo "1234" >"$ADDS/apps/localsend/data/pin.txt" 2>/dev/null || { mkdir -p "$ADDS/apps/localsend/data"; echo 1234 >"$ADDS/apps/localsend/data/pin.txt"; }
echo '{"remove":["gif"]}' >"$ADDS/koboapps/data/routing.json"
echo '{"repo":"me/mine","channel":"beta"}' >"$ADDS/koboapps/data/update.json"
mkdir -p "$ADDS/apps/todo/data" && echo '{"version":1,"tasks":[{"text":"Mua sữa","done":false}]}' >"$ADDS/apps/todo/data/todo.json"
echo "waiting" >"$ADDS/koboapps/inbox/pending.pdf"
cp "$ADDS/nm/items" "$WORK/items.after-first"
echo "stale" >"$ADDS/apps/ghsync/bin/obsolete.sh"
echo '{"version":0}' >"$ADDS/koboapps/config/routing.json"
sleep 1
"$INSTALLER" >"$WORK/second.out"
check "token preserved" contains "$ADDS/apps/ghsync/data/token" "secret-token"
check "config preserved" contains "$ADDS/apps/ghsync/data/config.json" '"o/r"'
check "todo list preserved" contains "$ADDS/apps/todo/data/todo.json" "Mua sữa"
check "pin preserved" contains "$ADDS/apps/localsend/data/pin.txt" "1234"
check "user update.json never overwritten" contains "$ADDS/koboapps/data/update.json" '"me/mine"'
echo '{"repo": "", "channel": "beta"}' >"$ADDS/koboapps/data/update.json"
sleep 1
"$INSTALLER" >"$WORK/third.out"
check "empty repo in an existing update.json is filled" contains "$ADDS/koboapps/data/update.json" '"repo": "minhdangphuoc/NickelDrawer"'
check "the user's channel survives the fill" contains "$ADDS/koboapps/data/update.json" '"channel": "beta"'
echo '{"repo":"me/mine","channel":"beta"}' >"$ADDS/koboapps/data/update.json"
sleep 1
"$INSTALLER" >"$WORK/third.out"
check "a repo the user set is kept" contains "$ADDS/koboapps/data/update.json" '"me/mine"'
check "user routing.json never overwritten" contains "$ADDS/koboapps/data/routing.json" '"remove":["gif"]'
check "files waiting in the inbox kept" contains "$ADDS/koboapps/inbox/pending.pdf" "waiting"
check "shipped routing.json refreshed" contains "$ADDS/koboapps/config/routing.json" '"type": "epub"'
check "bin/ replaced (stale file gone)" test ! -e "$ADDS/apps/ghsync/bin/obsolete.sh"
check "tab setting idempotent (items identical after reinstall)" cmp -s "$ADDS/nm/items" "$WORK/items.after-first"
check "second backup holds the token" grep -rqF secret-token "$BACKUP_ROOT"/*/.adds/apps/ghsync/data/token

echo "--- tab line missing or switched on again"
cp "$ADDS/nm/items" "$WORK/items.backup"
grep -v "menu_main_15505_enabled" "$WORK/items.backup" >"$ADDS/nm/items"
sleep 1
"$INSTALLER" >/dev/null
check "tab line added when missing" contains "$ADDS/nm/items" "experimental:menu_main_15505_enabled:0"
sed 's/^experimental:menu_main_15505_enabled:0$/experimental :menu_main_15505_enabled: 1/' "$ADDS/nm/items" >"$WORK/items.on"
cp "$WORK/items.on" "$ADDS/nm/items"
sleep 1
"$INSTALLER" >/dev/null
check "tab switched off again when the user turned it on" contains "$ADDS/nm/items" "experimental:menu_main_15505_enabled:0"
check "no stale tab-on line left" lacks "$ADDS/nm/items" "menu_main_15505_enabled: 1"
printf 'menu_item :reader :Dark Mode :nickel_setting :toggle :dark_mode' >"$ADDS/nm/items"
sleep 1
"$INSTALLER" >/dev/null
check "tab line appended on its own line after a file without final newline" contains "$ADDS/nm/items" "experimental:menu_main_15505_enabled:0"
check "Dark Mode line intact after append" contains "$ADDS/nm/items" "menu_item :reader :Dark Mode :nickel_setting :toggle :dark_mode"
cp "$WORK/items.backup" "$ADDS/nm/items"
sed -i.bak 's/^experimental :menu_main_15505_enabled: 1$/experimental:menu_main_15505_enabled:0/' "$ADDS/nm/items" && rm -f "$ADDS/nm/items.bak"

echo "--- unsupported language still installs"
write_kobo_conf fr
sleep 1
"$INSTALLER" >"$WORK/french.out"
check "fr install completes" contains "$WORK/french.out" "Summary:"
write_kobo_conf vi

echo "--- host strings without a locales folder"
"$REPO_ROOT/build/appsctl-host" host-msg --locale vi --koboapps-dir "$WORK/no-such-koboapps" refresh.summary apps=2 >"$WORK/fallback.out"
check "missing locales folder shows English, not the key" contains "$WORK/fallback.out" "Refreshed: 2 apps"
"$REPO_ROOT/build/appsctl-host" update status --onboard-root "$KOBO_ROOT" --locale vi >"$WORK/update-status.out"
check "update status is localized before any update" contains "$WORK/update-status.out" "Chưa cập nhật lần nào."

echo "--- remove legacy"
sleep 1
"$INSTALLER" --remove-legacy >"$WORK/legacy.out"
check "legacy folder removed" test ! -e "$ADDS/localsend"
check "legacy start item removed" lacks "$ADDS/nm/items" "Nhận sách LocalSend"
check "legacy stop item removed" lacks "$ADDS/nm/items" "Dừng LocalSend"
check "no legacy path left in items" lacks "$ADDS/nm/items" ".adds/localsend/"
check "other items intact" contains "$ADDS/nm/items" "Library Reload"
expectedLines=$(($(wc -l <"$WORK/items.original") - 4))
check "exactly 4 lines removed" test "$(wc -l <"$ADDS/nm/items" | tr -d ' ')" = "$expectedLines"
legacyBackup=$(ls -d "$BACKUP_ROOT"/*/.adds/localsend 2>/dev/null | head -n 1 || true)
check "legacy folder backed up" test -n "$legacyBackup"
"$INSTALLER" --remove-legacy >/dev/null
check "remove-legacy is idempotent" lacks "$ADDS/nm/items" "LocalSend :"

echo "--- app helpers answer through the drawer API"
helperRoot=$WORK/helpers
mkdir -p "$helperRoot/bin" "$helperRoot/app"
printf '#!/bin/sh\necho "TEXT:$*"\n' >"$helperRoot/bin/appsctl"
chmod 755 "$helperRoot/bin/appsctl"
run_helper() {
    # $1 = NICKELDRAWER value (empty: command line), the rest is the snippet to run.
    local drawerFlag=$1
    shift
    env -i PATH="$PATH" NICKELDRAWER="$drawerFlag" sh -c '. "$1"; KOBOAPPS_ROOT=$2; shift 2; eval "$*"' sh \
        "$REPO_ROOT/dist/onboard/.adds/koboapps/lib/common.sh" "$helperRoot" "$@"
}
check "report: drawer gets only a toast signal" test "$(run_helper 1 'report saved app msg.saved')" = '{"toast":"saved"}'
check "report: command line gets the localized text" test "$(run_helper '' 'report saved app msg.saved')" = "TEXT:msg --app app msg.saved"
check "report_failure: drawer exits 0" run_helper 1 'report_failure failed app msg.x' >/dev/null
check "report_failure: command line exits 1" test "$(run_helper '' 'report_failure failed app msg.x >/dev/null; echo unreachable' || echo failed)" = failed
check "fail_with: drawer logs and answers with the failed toast" test "$(run_helper 1 "fail_with $helperRoot/app boom")" = '{"toast":"failed"}'
check "fail_with: reason went to the app log" contains "$helperRoot/app/data/log.txt" "boom"
check "run_quick_command: drawer failure never prints the command output" test "$(run_helper 1 "run_quick_command $helperRoot/app done sh -c 'echo secret prose; exit 3'")" = '{"toast":"failed"}'
check "run_quick_command: drawer success prints the toast only" test "$(run_helper 1 "run_quick_command $helperRoot/app done sh -c 'echo prose'")" = '{"toast":"done"}'
check "run_quick_command: command line prints the output" test "$(run_helper '' "run_quick_command $helperRoot/app done sh -c 'echo prose'")" = prose

echo "--- the Nickel mod"
make_mod_tgz() { # content marker, extra entry (optional)
    local pack=$WORK/pack
    rm -rf "$pack"
    mkdir -p "$pack/usr/local/Kobo/imageformats"
    echo "$1" >"$pack/usr/local/Kobo/imageformats/libnickeldrawer.so"
    if [ -n "${2:-}" ]; then mkdir -p "$pack/$(dirname "$2")" && echo x >"$pack/$2"; fi
    mkdir -p "$WORK/mod"
    (cd "$pack" && COPYFILE_DISABLE=1 tar czf "$MOD_TGZ" .)
}
STAGED=$KOBO_ROOT/.kobo/KoboRoot.tgz
make_mod_tgz v1
mkdir -p "$ADDS/nickeldrawer"
touch "$ADDS/nickeldrawer/uninstall" "$ADDS/nickeldrawer/screens" "$ADDS/nickeldrawer/no-screens"
sleep 1
"$INSTALLER" >"$WORK/mod1.out"
check "the new mod is staged as KoboRoot.tgz" cmp -s "$MOD_TGZ" "$STAGED"
check "the install says to reboot" contains "$WORK/mod1.out" "reboot the Kobo"
check "the staged archive is recorded for the next install" cmp -s "$MOD_TGZ" "$ADDS/koboapps/mod/KoboRoot-nickeldrawer.tgz"
check "a stale uninstall flag is removed" test ! -e "$ADDS/nickeldrawer/uninstall"
check "the old screens flag is removed" test ! -e "$ADDS/nickeldrawer/screens"
check "the user's own flags stay" test -e "$ADDS/nickeldrawer/no-screens"
rm -f "$STAGED" # Nickel consumed it at the reboot
sleep 1
"$INSTALLER" >"$WORK/mod2.out"
check "an unchanged mod is not staged again" test ! -e "$STAGED"
make_mod_tgz v2
sleep 1
"$INSTALLER" --no-mod >/dev/null
check "--no-mod stages nothing" test ! -e "$STAGED"
sleep 1
"$INSTALLER" >/dev/null
check "a changed mod is staged again" cmp -s "$MOD_TGZ" "$STAGED"
rm -f "$STAGED"
sleep 1
"$INSTALLER" --with-mod >/dev/null
check "--with-mod stages even an unchanged mod" cmp -s "$MOD_TGZ" "$STAGED"
make_mod_tgz v3
sleep 1
"$INSTALLER" >"$WORK/ours.out" 2>&1
check "our own archive still waiting is replaced by a newer build" cmp -s "$MOD_TGZ" "$STAGED"
check "...and the record follows it" cmp -s "$MOD_TGZ" "$ADDS/koboapps/mod/KoboRoot-nickeldrawer.tgz"
printf 'not our archive\n' >"$STAGED"
make_mod_tgz v4
sleep 1
"$INSTALLER" >"$WORK/busy.out" 2>&1
check "a foreign archive that is already waiting is not replaced" bash -c '[ -f "$1" ] && ! cmp -s "$0" "$1"' "$MOD_TGZ" "$STAGED"
check "the install still completes and warns" contains "$WORK/busy.out" "already waiting"
sleep 1
"$INSTALLER" --with-mod >/dev/null 2>&1 && busyStatus=0 || busyStatus=$?
check "--with-mod refuses when another archive waits" test "$busyStatus" -ne 0
rm -f "$STAGED"
make_mod_tgz v4 etc/passwd
sleep 1
"$INSTALLER" --with-mod >"$WORK/evil.out" 2>&1 && evilStatus=0 || evilStatus=$?
check "an archive with foreign files is refused" test "$evilStatus" -ne 0
check "nothing is staged from it" test ! -e "$STAGED"
make_mod_tgz v5
sleep 1
"$INSTALLER" --dry-run --with-mod >"$WORK/dry-mod.out"
check "a dry run stages nothing" test ! -e "$STAGED"
check "a dry run announces the staging" contains "$WORK/dry-mod.out" "[dry-run] cp"

echo "--- uninstall"
"$INSTALLER" --with-mod >/dev/null # leaves our archive waiting, as right after an install
echo "waiting" >"$ADDS/koboapps/inbox/pending.pdf"
echo "kept-token" >"$ADDS/apps/ghsync/data/token"
sleep 1
"$INSTALLER" --uninstall --dry-run </dev/null >"$WORK/uninstall-dry.out"
check "an uninstall dry run removes nothing" test -x "$ADDS/koboapps/bin/appsctl"
sleep 1
echo y | "$INSTALLER" --uninstall >"$WORK/uninstall.out"
check "the host folder is gone" test ! -e "$ADDS/koboapps/bin"
check "the apps are gone" test ! -e "$ADDS/apps/localsend/bin"
check "app data is kept when asked" contains "$ADDS/apps/ghsync/data/token" "kept-token"
check "received files in the inbox are kept" contains "$ADDS/koboapps/inbox/pending.pdf" "waiting"
check "the mod uninstall flag is written" test -e "$ADDS/nickeldrawer/uninstall"
check "the user's flags stay" test -e "$ADDS/nickeldrawer/no-screens"
check "our waiting archive is withdrawn" test ! -e "$STAGED"
check "the NickelMenu tab setting is restored" contains "$ADDS/nm/items" "experimental:menu_main_15505_enabled:1"
check "the tab line still appears once" test "$(grep -c "menu_main_15505_enabled" "$ADDS/nm/items")" = 1
check "other NickelMenu lines are untouched" contains "$ADDS/nm/items" "menu_item :reader :Dark Mode"
check "the uninstall backed up the apps" grep -rqF kept-token "$BACKUP_ROOT"/*/.adds/apps/ghsync/data/token
check "the uninstall says to reboot" contains "$WORK/uninstall.out" "reboot the Kobo"
sleep 1
"$INSTALLER" >/dev/null
check "installing again after an uninstall works" test -x "$ADDS/koboapps/bin/appsctl"
check "...and clears the pending uninstall flag" test ! -e "$ADDS/nickeldrawer/uninstall"
sleep 1
"$INSTALLER" --uninstall --purge </dev/null >/dev/null
check "--purge deletes the app data too" test ! -e "$ADDS/apps/ghsync"
check "--purge still keeps the inbox files" contains "$ADDS/koboapps/inbox/pending.pdf" "waiting"
"$INSTALLER" --purge >/dev/null 2>&1 && purgeStatus=0 || purgeStatus=$?
check "--purge alone is refused" test "$purgeStatus" -ne 0

echo "--- guards"
KOBO_ROOT=$WORK/nothing "$INSTALLER" >"$WORK/missing.out" 2>&1 && missingStatus=0 || missingStatus=$?
check "refuses a volume without .kobo" test "$missingStatus" -ne 0

echo "--- finding the volume"
mkdir -p "$WORK/mounts/KOBOeReader/.kobo"
env -u KOBO_ROOT KOBO_SEARCH_DIRS="$WORK/mounts" "$INSTALLER" --dry-run >"$WORK/detect.out" 2>&1 && detectStatus=0 || detectStatus=$?
check "auto-detects a KOBOeReader volume in a search dir" test "$detectStatus" -eq 0
check "...and uses that volume" grep -qF "$WORK/mounts/KOBOeReader/.adds" "$WORK/detect.out"
env -u KOBO_ROOT KOBO_SEARCH_DIRS="$WORK/empty-mounts" "$INSTALLER" --dry-run >"$WORK/detect-none.out" 2>&1 && detectNoneStatus=0 || detectNoneStatus=$?
check "reports a missing volume when none is found" test "$detectNoneStatus" -ne 0
check "...and says how to set KOBO_ROOT" grep -qF "KOBO_ROOT" "$WORK/detect-none.out"

if [ "$failures" -ne 0 ]; then
    echo "$failures check(s) failed"
    exit 1
fi
echo "all checks passed"
