// ---- Text fit: the shared vectors (lib/copperui/tests/text-vectors.json) ----

enum Op { OP_WRAP, OP_WRAP_LIMITED, OP_ELIDE, OP_ELIDE_MIDDLE };

struct TextVector {
    const char *name;
    Op op;
    const char *text;
    int width;
    int size;
    Family family;
    bool isBold;
    int maxLines;
    int expectedCount;
    const char *expected[6];
};

#include "text_vectors.inc" // generated by `make tokens`

static bool contains(const char *chars, unsigned codePoint)
{
    // The fake font's special letters are ASCII.
    for (; *chars; chars++) {
        if ((unsigned char)*chars == codePoint) {
            return true;
        }
    }
    return false;
}

// The deterministic font of the vectors: see the comment in text-vectors.json.
static int fakeWidth(const void *, const char *utf8, int byteCount, const TextRun &run)
{
    int units = 0;
    for (int i = 0; i < byteCount; i++) {
        unsigned char byte = (unsigned char)utf8[i];
        if ((byte & 0xC0) == 0x80) {
            continue; // a continuation byte belongs to the code point before it
        }
        if (contains(FAKE_WIDE_CHARS, byte)) {
            units += FAKE_WIDE_PERCENT;
        } else if (contains(FAKE_NARROW_CHARS, byte)) {
            units += FAKE_NARROW_PERCENT;
        } else {
            units += FAKE_DEFAULT_PERCENT;
        }
    }
    int width = units * run.size / 100;
    width = width * FAKE_FAMILY_PERCENT[run.family] / 100;
    return run.isBold ? width * FAKE_BOLD_PERCENT / 100 : width;
}

static const TextMeter FAKE_METER = {fakeWidth, 0};

static void expectedText(const TextVector &vector, char *out, int outSize)
{
    int used = 0;
    out[0] = '\0';
    for (int i = 0; i < vector.expectedCount; i++) {
        used += snprintf(out + used, outSize - used, "%s%s", i > 0 ? "\n" : "", vector.expected[i]);
    }
}

static void testSharedTextVectors()
{
    for (unsigned i = 0; i < sizeof(TEXT_VECTORS) / sizeof(TEXT_VECTORS[0]); i++) {
        const TextVector &vector = TEXT_VECTORS[i];
        TextRun run = {vector.size, vector.family, vector.isBold};
        char expected[512];
        expectedText(vector, expected, sizeof(expected));
        char out[512];
        int lines = 0;
        switch (vector.op) {
        case OP_WRAP:
            lines = wrapText(vector.text, vector.width, run, FAKE_METER, 0, out, sizeof(out));
            break;
        case OP_WRAP_LIMITED:
            lines = wrapText(vector.text, vector.width, run, FAKE_METER, vector.maxLines, out, sizeof(out));
            break;
        case OP_ELIDE:
        case OP_ELIDE_MIDDLE:
            elideText(vector.text, vector.width, run, FAKE_METER, vector.op == OP_ELIDE_MIDDLE, out, sizeof(out));
            lines = 1;
            break;
        }
        if (strcmp(expected, out) != 0 || (vector.op <= OP_WRAP_LIMITED && lines != vector.expectedCount)) {
            printf("FAIL text vector \"%s\": got \"%s\" (%d lines), expected \"%s\"\n", vector.name, out, lines, expected);
            failures++;
        }
    }
}

