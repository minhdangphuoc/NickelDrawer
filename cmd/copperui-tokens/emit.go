package main

import (
	"bytes"
	"fmt"
	"go/format"
	"strings"
)

const generatedNote = "Generated by cmd/copperui-tokens from lib/copperui/tokens/copperui.tokens.json. Do not edit; run `make tokens`."

func valueText(token Token) string {
	switch value := token.Value.(type) {
	case string:
		return fmt.Sprintf("%q", value)
	case bool:
		return fmt.Sprintf("%t", value)
	default:
		return fmt.Sprint(value)
	}
}

// emitCpp writes the C++11 header: static const values in copperui::v1 (no standard library)
// and string macros for building Qt style sheets at compile time.
func emitCpp(spec *Spec) []byte {
	var out bytes.Buffer
	fmt.Fprintf(&out, "// %s\n", generatedNote)
	fmt.Fprintf(&out, "// CopperUI %s\n", spec.Version)
	out.WriteString("#ifndef COPPERUI_TOKENS_H\n#define COPPERUI_TOKENS_H\n\n")
	out.WriteString("namespace copperui {\nnamespace v1 {\n\n")
	fmt.Fprintf(&out, "static const char *const VERSION = %q;\n", spec.Version)
	for _, group := range spec.Groups {
		fmt.Fprintf(&out, "\n// ---- %s ----\n", group.Name)
		for _, token := range group.Tokens {
			out.WriteString(cppDeclaration(token))
		}
	}
	out.WriteString("\n} // namespace v1\n} // namespace copperui\n\n")
	out.WriteString("// String forms for style sheets: \"font-size: \" COPPERUI_PX_TYPE_CAPTION_SIZE \";\"\n")
	for _, token := range spec.tokens() {
		out.WriteString(cppStyleMacro(token))
	}
	out.WriteString("\n#endif\n")
	return out.Bytes()
}

func cppDeclaration(token Token) string {
	name := cppName(token.ID)
	comment := token.Unit
	if token.Doc != "" {
		comment += ": " + token.Doc
	}
	switch token.Unit {
	case unitText:
		return fmt.Sprintf("static const char *const %s = %s; // %s\n", name, valueText(token), comment)
	case unitFlag:
		return fmt.Sprintf("static const bool %s = %s; // %s\n", name, valueText(token), comment)
	}
	return fmt.Sprintf("static const int %s = %s; // %s\n", name, valueText(token), comment)
}

func cppStyleMacro(token Token) string {
	name := cppName(token.ID)
	switch token.Unit {
	case unitPx:
		return fmt.Sprintf("#define COPPERUI_PX_%s \"%spx\"\n", name, valueText(token))
	case unitGrey:
		level, _ := intValue(token)
		return fmt.Sprintf("#define COPPERUI_GREY_%s \"#%02x%02x%02x\"\n", name, level, level, level)
	}
	return ""
}

// emitGo writes the Go constants of package copperui.
func emitGo(spec *Spec) ([]byte, error) {
	var out bytes.Buffer
	fmt.Fprintf(&out, "// %s\n\n", generatedNote)
	out.WriteString("// Package copperui holds the CopperUI design tokens as Go constants.\npackage copperui\n\n")
	fmt.Fprintf(&out, "// Version is the CopperUI version the tokens belong to.\nconst Version = %q\n", spec.Version)
	for _, group := range spec.Groups {
		fmt.Fprintf(&out, "\n// %s\nconst (\n", group.Name)
		for _, token := range group.Tokens {
			comment := token.Unit
			if token.Doc != "" {
				comment += ": " + token.Doc
			}
			fmt.Fprintf(&out, "\t%s = %s // %s\n", goName(token.ID), valueText(token), comment)
		}
		out.WriteString(")\n")
	}
	formatted, err := format.Source(out.Bytes())
	if err != nil {
		return nil, fmt.Errorf("the generated Go constants do not format: %w", err)
	}
	return formatted, nil
}

// emitMarkdown writes the token tables of docs/copperui-tokens.md.
func emitMarkdown(spec *Spec) []byte {
	var out bytes.Buffer
	fmt.Fprintf(&out, "<!-- %s -->\n\n", generatedNote)
	fmt.Fprintf(&out, "# CopperUI tokens %s\n\n", spec.Version)
	out.WriteString("Generated from `lib/copperui/tokens/copperui.tokens.json`; the rules behind them are in `docs/design-system.md`. ")
	out.WriteString("Every size is a device pixel on the Kobo Libra 2 panel (1264 x 1680, 300 ppi); greys are levels 0 (black) to 255 (white) on the panel's 16-level grid.\n")
	for _, group := range spec.Groups {
		fmt.Fprintf(&out, "\n## %s\n\n| Token | Value | Unit | C++ constant | Go constant | Notes |\n|---|---|---|---|---|---|\n", group.Name)
		for _, token := range group.Tokens {
			value := strings.Trim(valueText(token), `"`)
			fmt.Fprintf(&out, "| `%s` | %s | %s | `%s` | `%s` | %s |\n", token.ID, value, token.Unit, cppName(token.ID), goName(token.ID), escapePipes(token.Doc))
		}
	}
	return out.Bytes()
}

func escapePipes(text string) string {
	return strings.ReplaceAll(text, "|", `\|`)
}
