// Package nmconfig renders the generated NickelMenu config (see docs/spec/app-format.md).
package nmconfig

import (
	"fmt"
	"path"
	"sort"
	"strings"

	"koboapps/internal/manifest"
)

const header = "# generated by appsctl — do not edit\n"

// Paths are the device locations the generated commands point at.
type Paths struct {
	AppsRoot     string // folder holding one subfolder per app
	KoboappsRoot string // folder holding bin/appsctl
}

// Labels are the host menu texts, already translated; Errors includes the error count.
type Labels struct {
	Refresh      string
	Errors       string
	UpdateCheck  string
	UpdateStatus string
}

// The update scripts live in koboapps/bin. cmd_output must return in under 10 s, so the check
// script only starts the update in the background; the status item shows the result.
const (
	updateCheckScript  = "update-apply.sh"
	updateStatusScript = "update-status.sh"
	updateCheckMS      = 9500
	updateStatusMS     = 3000
)

// DefaultPaths returns the locations on the Kobo.
func DefaultPaths() Paths {
	return Paths{
		AppsRoot:     "/mnt/onboard/.adds/apps",
		KoboappsRoot: "/mnt/onboard/.adds/koboapps",
	}
}

// MaxAppItems is how many app items fit in the NickelMenu popup; NickelMenu cannot scroll.
const MaxAppItems = 6

// Render builds the whole config: app items sorted by (localized) name, an error item when
// errorCount > 0, the refresh item, and the update items only when hasUpdateConfig.
// Apps must already be localized.
func Render(apps []manifest.App, errorCount int, paths Paths, labels Labels, hasUpdateConfig bool) string {
	var out strings.Builder
	out.WriteString(header)
	for _, app := range sortedMenuApps(apps) {
		for _, action := range menuActions(app) {
			writeAction(&out, app, action, paths)
		}
	}
	appsctl := path.Join(paths.KoboappsRoot, "bin", "appsctl")
	if errorCount > 0 {
		fmt.Fprintf(&out, "menu_item :main :%s :cmd_output :2000 :%s errors\n", labels.Errors, appsctl)
	}
	fmt.Fprintf(&out, "menu_item :main :%s :cmd_output :5000 :%s refresh\n", labels.Refresh, appsctl)
	if hasUpdateConfig {
		writeUpdateItems(&out, paths, labels)
	}
	return out.String()
}

func writeUpdateItems(out *strings.Builder, paths Paths, labels Labels) {
	checkScript := path.Join(paths.KoboappsRoot, "bin", updateCheckScript)
	statusScript := path.Join(paths.KoboappsRoot, "bin", updateStatusScript)
	fmt.Fprintf(out, "menu_item :main :%s :nickel_wifi :autoconnect\n", labels.UpdateCheck)
	fmt.Fprintf(out, "  chain_success :cmd_output :%d :%s\n", updateCheckMS, checkScript)
	fmt.Fprintf(out, "menu_item :main :%s :cmd_output :%d :%s\n", labels.UpdateStatus, updateStatusMS, statusScript)
}

// ItemCount is the number of menu items generated for apps (excluding the system items).
func ItemCount(apps []manifest.App) int {
	count := 0
	for _, app := range apps {
		if app.InMenu() {
			count += len(menuActions(app))
		}
	}
	return count
}

func menuActions(app manifest.App) []manifest.Action {
	var shown []manifest.Action
	for _, action := range app.Actions {
		if action.InMenu() {
			shown = append(shown, action)
		}
	}
	return shown
}

func sortedMenuApps(apps []manifest.App) []manifest.App {
	var shown []manifest.App
	for _, app := range apps {
		if app.InMenu() {
			shown = append(shown, app)
		}
	}
	sort.SliceStable(shown, func(i, j int) bool {
		if shown[i].Name != shown[j].Name {
			return shown[i].Name < shown[j].Name
		}
		return shown[i].ID < shown[j].ID
	})
	return shown
}

func writeAction(out *strings.Builder, app manifest.App, action manifest.Action, paths Paths) {
	title := app.Name + " · " + action.Label
	command := runCommand(action, path.Join(paths.AppsRoot, app.ID, action.Run))
	if action.Wifi {
		fmt.Fprintf(out, "menu_item :main :%s :nickel_wifi :autoconnect\n", title)
		fmt.Fprintf(out, "  chain_success :%s\n", command)
	} else {
		fmt.Fprintf(out, "menu_item :main :%s :%s\n", title, command)
	}
	switch action.RescanMode() {
	case manifest.RescanQuick:
		out.WriteString("  chain_success :nickel_misc :rescan_books\n")
	case manifest.RescanFull:
		out.WriteString("  chain_success :nickel_misc :rescan_books_full\n")
	}
}

func runCommand(action manifest.Action, scriptPath string) string {
	if action.Output == manifest.OutputNone {
		return "cmd_spawn :quiet :" + scriptPath
	}
	return fmt.Sprintf("cmd_output :%d :%s", action.Timeout(), scriptPath)
}
